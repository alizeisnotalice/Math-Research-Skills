#!/usr/bin/env python3
"""Check finite cyclic-group membership and nonmembership certificates exactly."""

from __future__ import annotations

import argparse
import json
from math import gcd
from math import gcd


def check_modulus(modulus: int) -> None:
    if modulus < 2:
        raise ValueError("modulus must be at least 2")


def group_element(value: int, modulus: int, label: str) -> int:
    reduced = value % modulus
    if reduced == 0:
        raise ValueError(f"{label} is not a unit modulo modulus")
    if gcd(reduced, modulus) != 1:
        raise ValueError(f"{label} is not a unit modulo modulus")
    return reduced


def nonmembership_certificate(modulus: int, generator: int, target: int, exponent: int) -> dict[str, object]:
    """Verify g**e = 1 and h**e != 1, a sufficient nonmembership certificate."""
    check_modulus(modulus)
    if exponent < 1:
        raise ValueError("exponent must be positive")
    generator = group_element(generator, modulus, "generator")
    target = group_element(target, modulus, "target")
    generator_power = pow(generator, exponent, modulus)
    target_power = pow(target, exponent, modulus)
    valid = generator_power == 1 and target_power != 1
    return {
        "modulus": modulus,
        "generator": generator,
        "target": target,
        "exponent": exponent,
        "generator_power": generator_power,
        "target_power": target_power,
        "certified_nonmember": valid,
        "scope": "If g^E=1 and h^E!=1 in a group, then h is not in the subgroup generated by g.",
    }


def membership_witness(modulus: int, generator: int, target: int, exponent: int) -> dict[str, object]:
    """Verify a supplied equality g**x = h; this proves membership only for that x."""
    check_modulus(modulus)
    if exponent < 0:
        raise ValueError("witness exponent must be nonnegative")
    generator = group_element(generator, modulus, "generator")
    target = group_element(target, modulus, "target")
    computed = pow(generator, exponent, modulus)
    return {
        "modulus": modulus,
        "generator": generator,
        "target": target,
        "witness_exponent": exponent,
        "generator_power": computed,
        "certified_member": computed == target,
        "scope": "The equality g^x=h certifies only this supplied membership witness.",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("member", "nonmember"))
    parser.add_argument("modulus", type=int)
    parser.add_argument("generator", type=int)
    parser.add_argument("target", type=int)
    parser.add_argument("exponent", type=int)
    args = parser.parse_args()
    try:
        result = (
            membership_witness(args.modulus, args.generator, args.target, args.exponent)
            if args.mode == "member"
            else nonmembership_certificate(args.modulus, args.generator, args.target, args.exponent)
        )
    except ValueError as error:
        parser.error(str(error))
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
